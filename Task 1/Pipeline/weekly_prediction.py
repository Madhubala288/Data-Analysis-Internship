import pandas as pd
import pickle
import os
import yagmail
from datetime import datetime
# 1. Define folder and file paths
MODEL_PATH = "../Notebook/models/logistic_model.pkl"
SCALER_PATH = "../Notebook/models/scaler.pkl"
INPUT_PATH = "input/new_customer_data.csv"
OUTPUT_DIR = "output"
print(" Automated Weekly Pipeline Started...")
# 2. Check if a new customer data file exists in the input directory
if not os.path.exists(INPUT_PATH):
    print(f" Error: No new data found at {INPUT_PATH}.")
else:
    # Load the pre-trained Logistic Regression model
    with open(MODEL_PATH, "rb") as f:
        model = pickle.load(f)    
    # Load the saved data scaler pipeline
    with open(SCALER_PATH, "rb") as f:
        scaler = pickle.load(f)    
    # Read the newly arrived weekly customer dataset
    data = pd.read_csv(INPUT_PATH) 
    # Extract the specific numerical features used during model training
    features = data[['tenure', 'MonthlyCharges']] 
    # Standardize the features using the loaded scaler
    scaled_features = scaler.transform(features)
    # Calculate churn probability scores using the machine learning model
    probability = model.predict_proba(scaled_features)[:, 1]
    data["Churn_Probability"] = probability
    # Segment customers into risk tiers (Low, Medium, High) based on probability thresholds
    data["Risk"] = pd.cut(probability, bins=[0, 0.3, 0.7, 1], labels=["Low", "Medium", "High"]) 
    # Save the processed report as a CSV file named with the current execution date
    current_date = datetime.now().date()
    output_file = os.path.join(OUTPUT_DIR, f"weekly_churn_report_{current_date}.csv")
    data.to_csv(output_file, index=False)
    print(f" Success! Weekly report saved at: {output_file}")
    
